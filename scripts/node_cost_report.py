# $PY scripts/node_cost_report.py LOG_OR_DIR [LOG_OR_DIR ...] [--probe evals/hen/runs/<date>-node-snapshot-probe.md]
"""Print the dollar-cost report (B1), the prompt-cache diagnostics (B2) and the off-node action
counts (B5/B6) for finished `farm_node_task` logs, as markdown on stdout.

Reads logs only; no model is called. Logs are read one at a time (the machine has little memory to
spare). Prices come from `scripts/model_prices.yml`; the sweep projection uses the runtime session
counts of a `scripts/probe_node_snapshots.py` report when `--probe` is given.
"""
import argparse
import gc
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from inspect_ai.log import read_eval_log  # noqa: E402

from farm_eval.config_paths import from_root  # noqa: E402
from farm_eval.env.loader import load_schedule  # noqa: E402
from farm_eval.report import cost  # noqa: E402


def _log_files(paths: list[str]) -> list[pathlib.Path]:
    out: list[pathlib.Path] = []
    for p in map(pathlib.Path, paths):
        out.extend(sorted(p.glob("*.eval")) if p.is_dir() else [p])
    return out


def _shown(path: pathlib.Path) -> str:
    """A path for the report: relative to the cwd when under it, else with the home dir as ~."""
    p = path.resolve()
    try:
        return str(p.relative_to(pathlib.Path.cwd()))
    except ValueError:
        home = pathlib.Path.home()
        return f"~/{p.relative_to(home)}" if p.is_relative_to(home) else str(p)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("logs", nargs="+", help=".eval files or directories of them")
    ap.add_argument("--prices", default=from_root("scripts/model_prices.yml"))
    ap.add_argument("--schedule", default=from_root("schedule"),
                    help="schedule dir used to attribute actions to decisions (default: this checkout's)")
    ap.add_argument("--probe", help="a probe_node_snapshots.py report, for the sweep projection")
    ap.add_argument("--rates", help="comma-separated rate names to show (default: every rate of each model)")
    ap.add_argument("--k", default="1,5", help="comma-separated k values for the sweep projection")
    ap.add_argument("--title", default="Node-episode cost report")
    args = ap.parse_args()

    prices = cost.load_prices(args.prices)
    schedule = load_schedule(args.schedule)
    rows: list[cost.EpisodeCost] = []
    files = _log_files(args.logs)
    for f in files:
        log = read_eval_log(str(f))
        rows.extend(cost.episodes_from_log(log, schedule, log_name=f.name))
        del log
        gc.collect()

    rate_names = [r.strip() for r in args.rates.split(",") if r.strip()] if args.rates else None
    probe = cost.parse_probe_sessions(pathlib.Path(args.probe).read_text(encoding="utf-8")) if args.probe else None

    print(f"# {args.title}")
    print()
    print("Eval: hen")
    print()
    print(f"- Generated by `scripts/node_cost_report.py` from {len(files)} log file(s), {len(rows)} sample(s). "
          "No model was called.")
    print(f"- Prices: `scripts/{pathlib.Path(args.prices).name}`; rates shown: {', '.join(rate_names) if rate_names else 'all'}.")
    if args.probe:
        print(f"- Session counts for the projection: `{args.probe}`.")
    print("- Logs:")
    for f in files:
        print(f"    - `{_shown(f)}`")
    print()
    print(cost.render_markdown(rows, prices, rate_names=rate_names, probe_sessions=probe,
                               ks=[int(k) for k in args.k.split(",")]))


if __name__ == "__main__":
    main()
